-- « Autre » n'est plus une valeur proposée : supprimée si rien ne l'utilise.
DELETE FROM "Referential" r
WHERE r."label" = 'Autre' AND r."type" = 'sector'
  AND NOT EXISTS (SELECT 1 FROM "Company" WHERE "sector" = 'Autre')
  AND NOT EXISTS (SELECT 1 FROM "Opportunity" WHERE "sector" = 'Autre')
  AND NOT EXISTS (SELECT 1 FROM "Room" WHERE "sector" = 'Autre')
  AND NOT EXISTS (SELECT 1 FROM "User" WHERE 'Autre' = ANY("sectors"));

DELETE FROM "Referential" r
WHERE r."label" = 'Autre' AND r."type" = 'country'
  AND NOT EXISTS (SELECT 1 FROM "Company" WHERE "country" = 'Autre')
  AND NOT EXISTS (SELECT 1 FROM "Opportunity" WHERE "country" = 'Autre')
  AND NOT EXISTS (SELECT 1 FROM "User" WHERE "country" = 'Autre');
